def base_system_prompt(values: dict[str, str]) -> str:
    """Persona prompt without any mood fragment.

    Moods apply to chat replies only; summaries and profile updates use this as-is.
    """
    prompt = values.get("system_prompt") or DEFAULT_SYSTEM_PROMPT
    return f"{prompt}\n\n{FORWARD_FORMAT_NOTE}"


def summary_prompt(values: dict[str, str]) -> str:
    return values.get("summary_prompt") or DEFAULT_SUMMARY_PROMPT


def apply_chat_style(system_prompt: str, values: dict[str, str]) -> str:
    """Append the optional chat-only style after the persona and mood."""
    if values.get("de_llmify_enabled", "0").lower() not in {"1", "true", "on", "yes"}:
        return system_prompt
    style = values.get("de_llmify_prompt", "").strip() or DEFAULT_DE_LLMIFY_PROMPT
    return f"{system_prompt}\n\n{style}"


def profile_prompt(values: dict[str, str]) -> str:
    return values.get("profile_prompt") or DEFAULT_PROFILE_PROMPT
